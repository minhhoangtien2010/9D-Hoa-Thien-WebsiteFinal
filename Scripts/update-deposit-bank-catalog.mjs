// Refresh the compiled deposit bank catalogue from public, credential-free sources.
// Usage: node WebPage.Core/Scripts/update-deposit-bank-catalog.mjs YYYY-MM-DD
import { writeFile } from 'node:fs/promises';

const retrieved = process.argv[2];
if (!/^\d{4}-\d{2}-\d{2}$/.test(retrieved ?? '')) {
  throw new Error('Pass the retrieval date as YYYY-MM-DD.');
}

async function publicJson(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`Public bank catalogue returned HTTP ${response.status}.`);
  return response.json();
}

const [vietQr, sepay] = await Promise.all([
  publicJson('https://api.vietqr.io/v2/banks'),
  publicJson('https://vietqr.app/banks.json')
]);
if (vietQr.code !== '00' || !Array.isArray(vietQr.data) || vietQr.data.length < 40 || !Array.isArray(sepay.data)) {
  throw new Error('Unexpected public bank catalogue response. Existing source has not been changed.');
}

const bins = new Set();
const stringLiteral = value => JSON.stringify(value ?? '');
const rows = vietQr.data.map(bank => {
  if (!/^\d{6}$/.test(bank.bin) || bins.has(bank.bin) || !bank.code || !bank.name || !bank.shortName) {
    throw new Error('Invalid or duplicate bank identifier. Existing source has not been changed.');
  }
  bins.add(bank.bin);
  const aliases = new Set();
  for (const matching of sepay.data.filter(other => other.bin === bank.bin)) {
    for (const value of [matching.name, matching.code, matching.short_name, ...(matching.alias ?? [])]) {
      if (typeof value === 'string' && value.trim()) aliases.add(value);
    }
  }
  const ownNames = [bank.name, bank.code, bank.bin, bank.shortName, bank.short_name];
  const extraNames = [...aliases].filter(alias => !ownNames.includes(alias));
  const aliasSource = extraNames.length
    ? `Array.AsReadOnly(new[] { ${extraNames.map(stringLiteral).join(', ')} })`
    : 'Array.Empty<string>()';
  return `        new(${ownNames.map(stringLiteral).join(', ')}, ${aliasSource})`;
});

const source = `// Generated by Scripts/update-deposit-bank-catalog.mjs; retrieved ${retrieved}.
// Primary source: https://api.vietqr.io/v2/banks (https://www.vietqr.io/api-bank).
// Additional same-BIN aliases: https://vietqr.app/banks.json,
// documented by https://developer.sepay.vn/vi/tien-ich-khac/tao-qr-code.
// This is an offline identifier snapshot, not proof that an account is linked to SePay.
using System.Collections.ObjectModel;
using System.Globalization;
using System.Text;

namespace WebPage.Helper;

public sealed record DepositBank(
    string Name, string Code, string Bin, string ShortName, string ShortNameLegacy,
    IReadOnlyList<string> Aliases);

/// <summary>Offline bank identity matching. Unknown and ambiguous identifiers fail closed.</summary>
public static class DepositBankCatalog
{
    private static readonly DepositBank[] Banks =
    [
${rows.join(',\n')}
    ];

    private static readonly IReadOnlyDictionary<string, DepositBank?> ByIdentifier = BuildIdentifiers();

    /// <summary>Known identifiers only; this does not verify SePay linkage or webhook configuration.</summary>
    public static IReadOnlyList<DepositBank> Options { get; } =
        Array.AsReadOnly(Banks.OrderBy(bank => bank.ShortName, StringComparer.OrdinalIgnoreCase).ToArray());

    public static DepositBank? Find(string? value) =>
        ByIdentifier.TryGetValue(Normalize(value), out var bank) ? bank : null;

    public static string? CanonicalBin(string? value) => Find(value)?.Bin;

    public static bool IsSupported(string? value) => Find(value) is not null;

    public static bool SameBank(string? expected, string? actual)
    {
        var expectedBank = Find(expected);
        var actualBank = Find(actual);
        return expectedBank is not null && actualBank is not null && expectedBank.Bin == actualBank.Bin;
    }

    private static IReadOnlyDictionary<string, DepositBank?> BuildIdentifiers()
    {
        var identifiers = new Dictionary<string, DepositBank?>(StringComparer.Ordinal);
        foreach (var bank in Banks)
        {
            foreach (var value in new[] { bank.Name, bank.Code, bank.Bin, bank.ShortName, bank.ShortNameLegacy }.Concat(bank.Aliases))
            {
                var key = Normalize(value);
                if (key.Length == 0) continue;
                if (identifiers.TryGetValue(key, out var existing) && existing?.Bin != bank.Bin)
                    identifiers[key] = null; // Never choose between two different banks sharing an alias.
                else if (!identifiers.ContainsKey(key))
                    identifiers.Add(key, bank);
            }
        }
        return new ReadOnlyDictionary<string, DepositBank?>(identifiers);
    }

    private static string Normalize(string? value)
    {
        if (string.IsNullOrWhiteSpace(value) || value.Length > 256) return string.Empty;
        string decomposed;
        try { decomposed = value.Normalize(NormalizationForm.FormD); }
        catch (ArgumentException) { return string.Empty; }
        var result = new StringBuilder(decomposed.Length);
        foreach (var character in decomposed)
        {
            var category = CharUnicodeInfo.GetUnicodeCategory(character);
            if (category is UnicodeCategory.NonSpacingMark or UnicodeCategory.SpacingCombiningMark or UnicodeCategory.EnclosingMark)
                continue;
            if (character is 'đ' or 'Đ') result.Append('D');
            else if (char.IsLetterOrDigit(character)) result.Append(char.ToUpperInvariant(character));
        }
        return result.ToString();
    }
}
`;

await writeFile(new URL('../Helper/DepositBankCatalog.cs', import.meta.url), source, 'utf8');
console.log(`Updated offline bank catalogue: ${rows.length} identifiers, retrieved ${retrieved}.`);
